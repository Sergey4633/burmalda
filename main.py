print("Привет, это словарь сленговых слов")
meme_dict = {
    "КРИНЖ": "Что-то очень странное или стыдное",
    "ЛОЛ": "Что-то очень смешное",
    "РОФЛ": "шутка",
    "КРИПОВЫЙ": "страшный, пугающий",
    "АГРИТЬСЯ": "злиться",
    "ИЗИ": "легко"
}
for i in range(5):
    print("Сленговые слова в словаре:", meme_dict.keys())
    
    word = input("Введите непонятное слово (большими буквами!): ").upper()
    
    if word in meme_dict.keys():
        # Что делать, если слово нашлось?
        print("{} означает {}".format(word, meme_dict[word]))
    else:
        # Что делать, если слово не нашлось?
        print("Такого слова нет в словаре")
